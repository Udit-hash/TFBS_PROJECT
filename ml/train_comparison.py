"""Train and compare the three sequence models and the DNA-shape fusion model."""

from __future__ import annotations

import argparse
import json
import random
from pathlib import Path

import numpy as np
import torch
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import train_test_split
from torch import nn
from torch.utils.data import DataLoader, Dataset

from config import (
    BATCH_SIZE,
    DEVICE,
    EPOCHS,
    LEARNING_RATE,
    MODEL_DIR,
    RANDOM_SEED,
    SEQUENCE_LENGTH,
)
from dna_shape import FEATURE_NAMES, PREDICTOR_NAME
from models.cnn import TFBS_CNN
from models.cnn_bilstm import TFBS_CNN_BiLSTM
from models.hybrid import TFBS_TriBranch
from models.shape_fusion import TFBS_TriBranchShape
from preprocessing import clean_sequence, one_hot_encode


SHAPE_DATA_DIR = Path(__file__).resolve().parent / "data" / "processed" / "dna_shape"
MODEL_FACTORIES = (
    ("cnn", "CNN", TFBS_CNN),
    ("cnn_bilstm", "CNN + BiLSTM", TFBS_CNN_BiLSTM),
    ("tri_branch", "CNN + BiLSTM + Transformer", TFBS_TriBranch),
)


class ShapeDataset(Dataset):
    def __init__(
        self,
        sequences: np.ndarray,
        shape_features: np.ndarray,
        labels: np.ndarray,
    ) -> None:
        if not (len(sequences) == len(shape_features) == len(labels)):
            raise ValueError("Sequences, shape features, and labels must align.")
        self.sequences = sequences
        self.shape_features = shape_features
        self.labels = labels

    def __len__(self) -> int:
        return len(self.labels)

    def __getitem__(self, index: int):
        return (
            torch.from_numpy(one_hot_encode(str(self.sequences[index]))),
            torch.from_numpy(self.shape_features[index].astype(np.float32, copy=False)),
            torch.tensor(float(self.labels[index]), dtype=torch.float32),
        )


def load_shape_split(path: Path) -> dict[str, object]:
    if not path.is_file():
        raise FileNotFoundError(
            f"DNA-shape artifact is missing: {path}. "
            "Run prepare_shape_dataset.py first."
        )
    try:
        with np.load(path, allow_pickle=False) as artifact:
            data = {
                "sequences": artifact["sequences"].copy(),
                "labels": artifact["labels"].copy(),
                "features": artifact["features"].copy(),
                "native_lengths": tuple(artifact["native_lengths"].tolist()),
                "feature_names": tuple(artifact["feature_names"].tolist()),
                "predictor": str(artifact["predictor"].item()),
                "predictor_version": str(artifact["predictor_version"].item()),
                "sequence_length": int(artifact["sequence_length"].item()),
                "schema_version": int(artifact["schema_version"].item()),
            }
    except (OSError, ValueError, KeyError) as exc:
        raise ValueError(f"Could not read DNA-shape artifact {path}: {exc}") from exc

    sequences = data["sequences"]
    labels = data["labels"]
    features = data["features"]
    if data["schema_version"] != 1:
        raise ValueError(f"{path} uses an unsupported feature-artifact schema.")
    if data["feature_names"] != FEATURE_NAMES:
        raise ValueError(f"{path} contains unexpected DNA-shape feature names.")
    if data["predictor"] != PREDICTOR_NAME:
        raise ValueError(f"{path} was not generated by {PREDICTOR_NAME}.")
    if data["sequence_length"] != SEQUENCE_LENGTH:
        raise ValueError(
            f"{path} uses {data['sequence_length']} bp; this run expects "
            f"{SEQUENCE_LENGTH} bp."
        )
    if (
        sequences.ndim != 1
        or len(sequences) == 0
        or labels.ndim != 1
        or features.ndim != 3
        or features.shape[:2] != (len(sequences), len(FEATURE_NAMES))
        or len(labels) != len(sequences)
        or features.shape[2] == 0
        or len(data["native_lengths"]) != len(FEATURE_NAMES)
        or min(data["native_lengths"], default=0) < 1
        or features.shape[2] != max(data["native_lengths"], default=0)
        or not np.isin(labels, [0, 1]).all()
        or np.isinf(features).any()
        or any(
            not np.isnan(features[:, index, length:]).all()
            for index, length in enumerate(data["native_lengths"])
        )
    ):
        raise ValueError(f"{path} has inconsistent sequences, labels, or features.")
    cleaned_sequences = [clean_sequence(sequence) for sequence in sequences]
    if cleaned_sequences != sequences.tolist():
        raise ValueError(f"{path} contains noncanonical or unnormalized sequences.")
    if len(set(cleaned_sequences)) != len(cleaned_sequences):
        raise ValueError(f"{path} contains duplicate sequences.")
    return data


def fit_shape_normalizer(training_features: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    if training_features.ndim != 3 or training_features.shape[1] != 4:
        raise ValueError("Training features must have shape [samples, 4, positions].")
    if np.isinf(training_features).any():
        raise ValueError("Training DNA-shape features cannot contain infinite values.")
    means = np.empty(4, dtype=np.float32)
    stds = np.empty(4, dtype=np.float32)
    for index, feature_values in enumerate(training_features.transpose(1, 0, 2)):
        valid_values = feature_values[np.isfinite(feature_values)]
        if valid_values.size == 0:
            raise ValueError(f"No valid training values for {FEATURE_NAMES[index]}.")
        means[index] = valid_values.mean(dtype=np.float64)
        deviation = valid_values.std(dtype=np.float64)
        stds[index] = deviation if deviation > 0 else 1.0
    return means, stds


def calculate_metrics(labels: np.ndarray, probabilities: np.ndarray) -> dict[str, float | None]:
    if labels.size == 0 or probabilities.size != labels.size:
        raise ValueError("Metrics require non-empty, equally sized labels and probabilities.")
    predictions = (probabilities >= 0.5).astype(np.int64)
    two_classes = np.unique(labels).size == 2
    has_positive = bool(np.any(labels == 1))
    return {
        "accuracy": float(accuracy_score(labels, predictions)),
        "precision": float(precision_score(labels, predictions, zero_division=0)),
        "recall": float(recall_score(labels, predictions, zero_division=0)),
        "f1": float(f1_score(labels, predictions, zero_division=0)),
        "roc_auc": float(roc_auc_score(labels, probabilities)) if two_classes else None,
        "pr_auc": float(average_precision_score(labels, probabilities)) if has_positive else None,
    }


def _forward(model: nn.Module, sequence: torch.Tensor, shape: torch.Tensor, use_shape: bool):
    return model(sequence, shape) if use_shape else model(sequence)


def evaluate_model(
    model: nn.Module,
    loader: DataLoader,
    use_shape: bool,
) -> tuple[dict[str, float | None], float]:
    model.eval()
    criterion = nn.BCEWithLogitsLoss()
    labels_all = []
    probabilities_all = []
    total_loss = 0.0
    total = 0
    with torch.no_grad():
        for sequence, shape, labels in loader:
            sequence = sequence.to(DEVICE)
            shape = shape.to(DEVICE)
            labels = labels.to(DEVICE).unsqueeze(1)
            logits = _forward(model, sequence, shape, use_shape)
            loss = criterion(logits, labels)
            count = sequence.shape[0]
            total_loss += loss.item() * count
            total += count
            labels_all.extend(labels.squeeze(1).cpu().numpy())
            probabilities_all.extend(torch.sigmoid(logits).squeeze(1).cpu().numpy())
    labels_np = np.asarray(labels_all, dtype=np.int64)
    probabilities_np = np.asarray(probabilities_all, dtype=np.float64)
    return calculate_metrics(labels_np, probabilities_np), total_loss / total


def _train_one(
    key: str,
    model_name: str,
    model: nn.Module,
    train_loader: DataLoader,
    validation_loader: DataLoader,
    test_loader: DataLoader,
    train_labels: np.ndarray,
    use_shape: bool,
    epochs: int,
    patience: int,
    metadata: dict[str, object],
) -> dict[str, object]:
    positive = int(np.sum(train_labels == 1))
    negative = int(np.sum(train_labels == 0))
    if positive == 0 or negative == 0:
        raise ValueError("Training data must contain both binary classes.")
    model = model.to(DEVICE)
    criterion = nn.BCEWithLogitsLoss(
        pos_weight=torch.tensor([negative / positive], dtype=torch.float32, device=DEVICE)
    )
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=LEARNING_RATE, weight_decay=5e-4
    )
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer, mode="max", factor=0.5, patience=3, min_lr=1e-6
    )
    checkpoint_path = MODEL_DIR / (
        "best_shape_fusion.pth" if use_shape else f"comparison_{key}.pth"
    )
    best_f1 = -1.0
    best_state = None
    stale_epochs = 0

    for epoch in range(epochs):
        model.train()
        total_loss = 0.0
        total = 0
        for sequence, shape, labels in train_loader:
            sequence = sequence.to(DEVICE)
            shape = shape.to(DEVICE)
            labels = labels.to(DEVICE).unsqueeze(1)
            optimizer.zero_grad(set_to_none=True)
            logits = _forward(model, sequence, shape, use_shape)
            loss = criterion(logits, labels)
            loss.backward()
            optimizer.step()
            count = sequence.shape[0]
            total_loss += loss.item() * count
            total += count

        validation_metrics, validation_loss = evaluate_model(
            model, validation_loader, use_shape
        )
        validation_f1 = float(validation_metrics["f1"])
        scheduler.step(validation_f1)
        print(
            f"{model_name} epoch {epoch + 1}/{epochs}: "
            f"train_loss={total_loss / total:.4f}, "
            f"val_loss={validation_loss:.4f}, val_f1={validation_f1:.4f}"
        )
        if validation_f1 > best_f1:
            best_f1 = validation_f1
            stale_epochs = 0
            best_state = {
                name: tensor.detach().cpu().clone()
                for name, tensor in model.state_dict().items()
            }
            torch.save(
                {
                    "model_type": key,
                    "model_state_dict": best_state,
                    **metadata,
                },
                checkpoint_path,
            )
        else:
            stale_epochs += 1
            if stale_epochs >= patience:
                print(f"{model_name}: early stopping after {epoch + 1} epochs.")
                break

    if best_state is None:
        raise RuntimeError(f"{model_name} did not produce a valid checkpoint.")
    model.load_state_dict(best_state)
    test_metrics, test_loss = evaluate_model(model, test_loader, use_shape)
    return {
        "model": model_name,
        "checkpoint": str(checkpoint_path),
        "test_loss": test_loss,
        **test_metrics,
    }


def train_comparison(
    train_path: Path,
    test_path: Path,
    epochs: int = EPOCHS,
    batch_size: int = BATCH_SIZE,
    seed: int = RANDOM_SEED,
    patience: int = 6,
) -> dict[str, dict[str, object]]:
    if epochs < 1 or batch_size < 1 or patience < 1:
        raise ValueError("epochs, batch_size, and patience must be positive.")
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)

    train = load_shape_split(train_path)
    test = load_shape_split(test_path)
    if train["predictor_version"] != test["predictor_version"]:
        raise ValueError("Train and test artifacts use different DNAshapeR versions.")
    overlap = set(train["sequences"]).intersection(test["sequences"])
    if overlap:
        raise ValueError(
            f"Train and test artifacts overlap by {len(overlap)} sequences."
        )
    if train["native_lengths"] != test["native_lengths"]:
        raise ValueError(
            "Train and test artifacts have different native lengths by feature."
        )
    labels = train["labels"]
    if np.unique(labels).size != 2 or np.min(np.bincount(labels)) < 2:
        raise ValueError("Training split needs at least two examples per class.")

    indices = np.arange(len(labels))
    train_indices, validation_indices = train_test_split(
        indices,
        test_size=0.15,
        random_state=seed,
        stratify=labels,
    )
    train_sequences = train["sequences"][train_indices]
    train_labels = labels[train_indices]
    train_features = train["features"][train_indices]
    validation_dataset = ShapeDataset(
        train["sequences"][validation_indices],
        train["features"][validation_indices],
        labels[validation_indices],
    )
    train_dataset = ShapeDataset(train_sequences, train_features, train_labels)
    test_dataset = ShapeDataset(test["sequences"], test["features"], test["labels"])
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
    validation_loader = DataLoader(
        validation_dataset, batch_size=batch_size, shuffle=False
    )
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

    print(
        "Class counts (train / validation / test): "
        f"{np.bincount(train_labels, minlength=2).tolist()} / "
        f"{np.bincount(labels[validation_indices], minlength=2).tolist()} / "
        f"{np.bincount(test['labels'], minlength=2).tolist()}"
    )
    results: dict[str, dict[str, object]] = {}
    common_metadata = {
        "sequence_length": SEQUENCE_LENGTH,
        "shape_feature_names": FEATURE_NAMES,
        "shape_positions": int(train["features"].shape[2]),
        "shape_native_lengths": train["native_lengths"],
        "shape_predictor": PREDICTOR_NAME,
        "shape_predictor_version": train["predictor_version"],
        "validation_fraction": 0.15,
        "random_seed": seed,
    }

    for key, name, model_factory in MODEL_FACTORIES:
        model = model_factory()
        results[key] = _train_one(
            key,
            name,
            model,
            train_loader,
            validation_loader,
            test_loader,
            train_labels,
            False,
            epochs,
            patience,
            common_metadata,
        )

    shape_mean, shape_std = fit_shape_normalizer(train_features)
    shape_model = TFBS_TriBranchShape(
        seq_len=SEQUENCE_LENGTH,
        shape_mean=torch.from_numpy(shape_mean),
        shape_std=torch.from_numpy(shape_std),
    )
    shape_metadata = {
        **common_metadata,
        "shape_mean": shape_mean.tolist(),
        "shape_std": shape_std.tolist(),
        "threshold": 0.5,
    }
    results["shape_fusion"] = _train_one(
        "tri_branch_dna_shape",
        "CNN + BiLSTM + Transformer + DNAshapeR",
        shape_model,
        train_loader,
        validation_loader,
        test_loader,
        train_labels,
        True,
        epochs,
        patience,
        shape_metadata,
    )

    results_path = MODEL_DIR / "dna_shape_comparison_results.json"
    results_path.parent.mkdir(parents=True, exist_ok=True)
    results_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"Comparison results saved to {results_path}")
    return results


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Fairly compare sequence-only models and the DNA-shape fusion model."
    )
    parser.add_argument("--epochs", type=int, default=EPOCHS)
    parser.add_argument("--batch-size", type=int, default=BATCH_SIZE)
    parser.add_argument("--seed", type=int, default=RANDOM_SEED)
    parser.add_argument("--patience", type=int, default=6)
    parser.add_argument("--train", type=Path, default=SHAPE_DATA_DIR / "train_shape.npz")
    parser.add_argument("--test", type=Path, default=SHAPE_DATA_DIR / "test_shape.npz")
    args = parser.parse_args()
    train_comparison(
        args.train,
        args.test,
        epochs=args.epochs,
        batch_size=args.batch_size,
        seed=args.seed,
        patience=args.patience,
    )


if __name__ == "__main__":
    main()
